// Own a loopback database; never load application dotenv files or live credentials.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createDisposablePostgres } from '../program-head/postgres-fixture.mjs';
import { repairRuntimeSchemaPermission } from '../../scripts/repair-runtime-schema-permission.mjs';

const fixture = await createDisposablePostgres();
const checks = [];
try {
  const owner = fixture.owner;
  await owner.query(`CREATE TABLE public."User"(id text PRIMARY KEY,allowed boolean NOT NULL DEFAULT true,CONSTRAINT privileged_admission_state CHECK(allowed));
    CREATE TABLE public."Session"(id text PRIMARY KEY); CREATE TABLE public."AuditLog"(id text PRIMARY KEY);
    INSERT INTO public."User" VALUES('synthetic-account',true); INSERT INTO public."Session" VALUES('synthetic-session'); INSERT INTO public."AuditLog" VALUES('synthetic-audit');
    CREATE SCHEMA super_user_security; REVOKE ALL ON SCHEMA super_user_security FROM PUBLIC;
    CREATE TABLE super_user_security.writer_bindings(principal name PRIMARY KEY,kind text,enabled boolean,qualification_reference text);
    INSERT INTO super_user_security.writer_bindings VALUES('bqual_test_app','APPLICATION',true,'OWNED_LOCAL_TEST_ONLY');
    CREATE FUNCTION super_user_security.test_guard() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$;
    CREATE TRIGGER super_user_guard BEFORE INSERT OR UPDATE OR DELETE ON public."User" FOR EACH ROW EXECUTE FUNCTION super_user_security.test_guard();
    CREATE TRIGGER operator_audit_guard BEFORE INSERT OR UPDATE OR DELETE ON public."AuditLog" FOR EACH ROW EXECUTE FUNCTION super_user_security.test_guard();
    CREATE TRIGGER privileged_session_guard BEFORE INSERT OR UPDATE ON public."Session" FOR EACH ROW EXECUTE FUNCTION super_user_security.test_guard();
    ALTER TABLE public."User" ENABLE ALWAYS TRIGGER super_user_guard;
    ALTER TABLE public."AuditLog" ENABLE ALWAYS TRIGGER operator_audit_guard;
    ALTER TABLE public."Session" ENABLE ALWAYS TRIGGER privileged_session_guard;
    GRANT USAGE ON SCHEMA super_user_security TO bqual_test_app;`);
  const sql = fs.readFileSync('prisma/super-user-v1/current-target-security.sql', 'utf8');
  const fn = 'CREATE FUNCTION super_user_security.application_boundary_qualified()' + sql.split('CREATE FUNCTION super_user_security.application_boundary_qualified()')[1].split('$$;')[0] + '$$;';
  await owner.query(fn);
  await owner.query('REVOKE ALL ON FUNCTION super_user_security.application_boundary_qualified() FROM PUBLIC; GRANT EXECUTE ON FUNCTION super_user_security.application_boundary_qualified() TO bqual_test_app');
  const runtime = await fixture.connect();
  const qualified = async () => (await runtime.query('SELECT super_user_security.application_boundary_qualified() AS value')).rows[0].value;
  const canCreate = async () => (await runtime.query("SELECT has_schema_privilege(session_user,'public','CREATE') AS value")).rows[0].value;
  const preserved = async () => (await owner.query(`SELECT (SELECT jsonb_agg(u ORDER BY id) FROM public."User" u) AS users,(SELECT jsonb_agg(s ORDER BY id) FROM public."Session" s) AS sessions,(SELECT jsonb_agg(a ORDER BY id) FROM public."AuditLog" a) AS audits`)).rows[0];
  const before = await preserved();
  assert.equal(await qualified(), true);
  await owner.query('GRANT CREATE ON SCHEMA public TO bqual_test_app');
  assert.equal(await qualified(), false);
  assert.equal(await canCreate(), true);
  checks.push('Reproduced administrator boundary rejection from the direct runtime public-schema CREATE grant using the repository qualification function');
  const result = await repairRuntimeSchemaPermission(owner, 'bqual_test_app');
  assert.equal(result.status, 'APPLIED');
  assert.equal(await qualified(), true);
  assert.equal(await canCreate(), false);
  await assert.rejects(runtime.query('CREATE TABLE public.forbidden_after_repair(id int)'), error => error.code === '42501');
  assert.deepEqual(await preserved(), before);
  checks.push('Repair restores qualification, denies schema creation, and preserves accounts, sessions, audit rows and enabled guards');
  assert.equal((await repairRuntimeSchemaPermission(owner, 'bqual_test_app')).status, 'ALREADY_RESTRICTED');
  checks.push('Repeating the repair makes no further changes');
  await owner.query('GRANT CREATE ON SCHEMA public TO bqual_test_app; UPDATE super_user_security.writer_bindings SET enabled=false');
  await assert.rejects(repairRuntimeSchemaPermission(owner, 'bqual_test_app'), /qualification binding/);
  assert.equal(await canCreate(), true);
  await owner.query('UPDATE super_user_security.writer_bindings SET enabled=true; GRANT CREATE ON SCHEMA public TO PUBLIC');
  await assert.rejects(repairRuntimeSchemaPermission(owner, 'bqual_test_app'), /rolled back/);
  assert.equal(await canCreate(), true);
  await owner.query('REVOKE CREATE ON SCHEMA public FROM PUBLIC');
  checks.push('A missing qualification binding or additional PUBLIC permission refuses/rolls back without partial changes');
  await owner.query('ALTER TABLE public."Session" DISABLE TRIGGER privileged_session_guard');
  await assert.rejects(repairRuntimeSchemaPermission(owner, 'bqual_test_app'), /always-enabled/);
  assert.equal(await canCreate(), true);
  await owner.query('ALTER TABLE public."Session" ENABLE ALWAYS TRIGGER privileged_session_guard');
  await owner.query('CREATE OR REPLACE FUNCTION super_user_security.application_boundary_qualified() RETURNS boolean LANGUAGE sql SECURITY DEFINER SET search_path=pg_catalog,super_user_security AS $$ SELECT true $$');
  await assert.rejects(repairRuntimeSchemaPermission(owner, 'bqual_test_app'), /Unexpected security function/);
  assert.equal(await canCreate(), true);
  assert.deepEqual(await preserved(), before);
  checks.push('Disabled guards and modified qualification functions cannot be silently accepted');
} finally { await fixture.stop(); }
const report = { status: 'PASS', checks, clusterStopped: true, liveDatabase: false };
fs.mkdirSync('tmp/lms-system-review', { recursive: true });
fs.writeFileSync('tmp/lms-system-review/runtime-permission-test.json', JSON.stringify(report, null, 2));
console.log(JSON.stringify(report));
