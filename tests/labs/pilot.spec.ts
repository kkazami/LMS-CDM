const state = JSON.parse(fs.readFileSync(process.env.LAB_E2E_STATE!, 'utf8'));
function modal(page: Page, name: string) { return page.getByRole('dialog', { name, exact: true }); }
async function focusedInView(control: Locator) {
  await expect(control).toBeFocused();
  await expect(control).toBeInViewport({ ratio: 1 });
}
async function login(page: Page, role: 'teacher' | 'student' | 'other') {
  await page.goto('/login?institute=ics');
  await page.getByLabel('Email or student ID', { exact: true }).fill(state.accounts[role].email);
  await page.getByLabel('Password', { exact: true }).fill(state.password);
  await page.getByRole('checkbox', { name: /I agree to the Terms and Conditions/ }).check();
  await page.getByRole('button', { name: /sign in/i }).click();
  await expect(page).toHaveURL(/\/ics(?:\/|$)/);
}

